#!/usr/bin/env python3
"""Build the launcher's app list (apps.js) and an icon-copy script for the TV.

The TV denies listApps to third-party apps, so the launcher ships a baked list.
Icons are copied on-device by the root payload (they live in the app folders,
and the TV's own icon URLs aren't fetchable remotely)."""
import json
import os
import sys
import time

sys.path.insert(0, os.path.expanduser("~/slopbro"))
os.chdir(os.path.expanduser("~/slopbro"))
import slopbro as sb  # noqa: E402

HOST = os.environ.get("TV_IP") or "192.168.0.10"
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

HIDDEN = [
    "com.webos.app.externalinput",
    "com.webos.app.dp",
    "com.webos.app.adapp",
    "com.webos.app.adhdmi",
    "com.webos.app.adoverlay",
    "com.webos.app.acr",
    "com.webos.app.cpcover",
    "com.webos.app.bootlogo",
    "com.webos.app.firstuse",
    "com.webos.app.factorywin",
    "com.webos.app.helpandtips",
    "com.webos.app.channeledit",
    "com.webos.app.channelsetting",
    "com.webos.app.livetvopapp",
    "com.webos.app.lgchannels",
]

PINNED = [
    "com.webos.app.livetv",
    "com.webos.app.hdmi1",
    "com.webos.app.hdmi2",
    "com.webos.app.hdmi3",
    "com.webos.app.hdmi4",
]

# Included even though LG marks them non-visible.
FORCE_INCLUDE = {
    "com.webos.app.livetv",
    "com.webos.app.hdmi1",
    "com.webos.app.hdmi2",
    "com.webos.app.hdmi3",
    "com.webos.app.hdmi4",
    "com.palm.app.settings",
}

HDMI_PREFIX = "com.webos.app.hdmi"


def icon_candidates(app):
    """Return ([(dir, filename), ...], remote_url) for an app's icon."""
    folder = app.get("folderPath") or ""
    base = app.get("sysAssetsBasePath") or ""
    out = []
    for field in ("largeIcon", "extraLargeIcon", "mediumLargeIcon", "mediumIcon"):
        value = app.get(field)
        if value and not str(value).startswith("http"):
            out.append((folder, value))
    icon = app.get("icon") or ""
    remote = icon if icon.startswith("http") else ""
    if icon and not remote:
        rel = os.path.join(base, icon) if base else icon
        out.append((folder, rel))
    return out, remote


def main():
    ws = sb.WebSocket.connect(HOST, sb.PORT_TLS, secure=True)
    client = sb.SSAPClient(ws)
    key = sb.load_client_key(HOST)
    new_key = client.register(key, sb.DEFAULT_MANIFEST)
    if new_key and new_key != key:
        sb.save_client_key(HOST, new_key)
    resp = client.request(
        "ssap://com.webos.applicationManager/listApps", {}, timeout=15.0
    )
    apps = (resp.get("payload") or {}).get("apps") or []
    client.close()

    entries = []
    seen = set()
    for app in apps:
        app_id = app.get("id")
        title = app.get("title")
        if not app_id or not title or app_id in seen:
            continue
        if app_id not in FORCE_INCLUDE:
            if app.get("visible") is False:
                continue
            if any(app_id.startswith(h) for h in HIDDEN):
                continue
        seen.add(app_id)
        if app_id.startswith(HDMI_PREFIX) and app_id[len(HDMI_PREFIX):].isdigit():
            title = "HDMI " + app_id[len(HDMI_PREFIX):]
        cands, remote = icon_candidates(app)
        entries.append(
            {
                "id": app_id,
                "title": title,
                "iconColor": app.get("iconColor") or "",
                "iconLocal": "icons/apps/%s.png" % app_id,
                "folder": app.get("folderPath") or "",
                "cands": cands,
                "remote": remote,
            }
        )

    def sort_key(entry):
        if entry["id"] in PINNED:
            return (0, PINNED.index(entry["id"]))
        return (1, entry["title"].lower())

    entries.sort(key=sort_key)

    # --- apps.js -------------------------------------------------------------
    baked = [
        {
            "id": e["id"],
            "title": e["title"],
            "icon": e["iconLocal"],
            "iconColor": e["iconColor"],
        }
        for e in entries
    ]
    apps_js = os.path.join(ROOT, "app", "js", "apps.js")
    with open(apps_js, "w") as fh:
        fh.write("/* generated by tools/fetch_apps.py at %s */\n" % time.strftime("%Y-%m-%d %H:%M"))
        fh.write("window.TVL_APPS = ")
        json.dump(baked, fh, indent=2)
        fh.write(";\n")

    # --- copy_icons.sh -------------------------------------------------------
    lines = [
        "# generated by tools/fetch_apps.py at %s" % time.strftime("%Y-%m-%d %H:%M"),
        "ICON_EXPECTED=%d" % len(entries),
    ]
    for e in entries:
        for folder, rel in e["cands"]:
            lines.append('copy_icon "%s" "%s" "%s" ""' % (e["id"], folder, rel))
        if e["folder"]:
            lines.append('copy_icon "%s" "%s" "icon.png" ""' % (e["id"], e["folder"]))
            lines.append('copy_icon "%s" "%s" "largeIcon.png" ""' % (e["id"], e["folder"]))
            lines.append('copy_icon "%s" "%s" "" ""' % (e["id"], e["folder"]))
        if e["remote"]:
            lines.append('copy_icon "%s" "" "" "%s"' % (e["id"], e["remote"]))
    copy_sh = os.path.join(ROOT, "rootrun", "copy_icons.sh")
    with open(copy_sh, "w") as fh:
        fh.write("\n".join(lines) + "\n")

    print("baked %d apps (pinned: %s)" % (len(entries), ", ".join(e["id"] for e in entries[:6])))
    print("wrote", apps_js)
    print("wrote", copy_sh)


if __name__ == "__main__":
    main()
